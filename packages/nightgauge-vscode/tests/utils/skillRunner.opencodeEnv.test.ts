/**
 * skillRunner.opencodeEnv.test.ts (Issue #1657)
 *
 * The editor's `opencode` stage through the REAL dispatch path
 * (`runStageSkillHeadless`), at the `child_process.spawn` seam the grok and
 * adapter-perf-mode suites use:
 *
 *   - the spawn env: the dispatch model, and none of the operator's
 *     `OPENCODE_*` variables or other providers' keys; then, composed with the
 *     SDK's own `curateOpenCodeChildEnv` and the Go verb's golden output, the
 *     env the `opencode` process itself gets;
 *   - a performance-mode band on a local configured model keeps that model and
 *     records the source as `config`;
 *   - liveness: step-level progress lines reset the idle clock that drives
 *     the stall kill, and a local model's stage is neither warned about nor
 *     killed before the local floor.
 */
