describe("opencode spawn env (#1657)", () => {
  beforeEach(() => {
    process.env.OPENCODE_PERMISSION = '{"*":"allow"}';
    process.env.NIGHTGAUGE_OPENCODE_PLUGIN_NONCE = "outer-run-nonce";
    process.env.XDG_CONFIG_HOME = "/operator/xdg-config";
    process.env.OPENAI_API_KEY = "sk-operator-openai";
    process.env.LMSTUDIO_API_KEY = "lm-operator";
    process.env.GITHUB_TOKEN = "ghp-forge";
  });

  it("carries the dispatch model and no operator OPENCODE_* or other provider's key", () => {
    dispatch("feature-dev", LOCAL_MODEL);
    const env = lastSpawnEnv();

    expect(env.NIGHTGAUGE_MODEL).toBe(LOCAL_MODEL);
    expect(env.NIGHTGAUGE_ADAPTER).toBe("opencode");
    expect(env).not.toHaveProperty("OPENCODE_PERMISSION");
    expect(env).not.toHaveProperty("OPENAI_API_KEY");
    // The selected provider's own variable and the forge token stay.
    expect(env.LMSTUDIO_API_KEY).toBe("lm-operator");
    expect(env.GITHUB_TOKEN).toBeDefined();
    // Kept on purpose: the `nightgauge opencode config` run the SDK starts in
    // this env reads the operator's XDG base to pin gh, GOCACHE and the
    // machine config back (see reconcileOpenCodeSpawnEnv).
    expect(env.XDG_CONFIG_HOME).toBe("/operator/xdg-config");
    expect(env.NIGHTGAUGE_EXPERIMENTAL_OPENCODE).toBe("1");
  });

  it("keeps a hosted provider's key and drops the rest", () => {
    process.env.ANTHROPIC_API_KEY = "sk-ant-operator";
    dispatch("feature-dev", "anthropic/claude-sonnet-5");
    const env = lastSpawnEnv();
    expect(env.NIGHTGAUGE_MODEL).toBe("anthropic/claude-sonnet-5");
    expect(env.ANTHROPIC_API_KEY).toBe("sk-ant-operator");
    expect(env).not.toHaveProperty("OPENAI_API_KEY");
    expect(env).not.toHaveProperty("LMSTUDIO_API_KEY");
  });

  it("withholds exactly the Go verb's env_withhold for the model, and keeps platform credentials", async () => {
    const verb = await goldenVerb();
    for (const name of verb.env_withhold.names) process.env[name] = `operator-${name}`;
    process.env.AWS_SECRET_ACCESS_KEY = "aws-operator";
    process.env.OPENCODE_ANYTHING_NEW = "x";
    dispatch("feature-dev", LOCAL_MODEL);
    const env = lastSpawnEnv();
    const leaked = verb.env_withhold.names.filter((n) => n in env);
    expect(leaked).toEqual([]);
    expect(Object.keys(env).filter((n) => n.startsWith("OPENCODE_"))).toEqual([]);
    expect(env.AWS_SECRET_ACCESS_KEY).toBe("aws-operator");
    expect(env.LMSTUDIO_API_KEY).toBe("lm-operator");
  });

  it("the opencode process the SDK spawns from it gets the Go verb's values and none of the three", async () => {
    dispatch("feature-dev", LOCAL_MODEL);
    const verb = await goldenVerb();
    const child = curateOpenCodeChildEnv(lastSpawnEnv(), LOCAL_MODEL, verb.env);

    expect(child).not.toHaveProperty("OPENCODE_PERMISSION");
    expect(child.NIGHTGAUGE_OPENCODE_PLUGIN_NONCE).toBe(verb.env.NIGHTGAUGE_OPENCODE_PLUGIN_NONCE);
    expect(child).not.toHaveProperty("OPENAI_API_KEY");
    expect(child.XDG_CONFIG_HOME).toBe(verb.env.XDG_CONFIG_HOME);
    expect(child.XDG_CONFIG_HOME).not.toBe("/operator/xdg-config");
    expect(child.OPENCODE_CONFIG_CONTENT).toBe(verb.config_content);
    for (const [name, value] of Object.entries(verb.env)) {
      expect(child[name], name).toBe(value);
    }
  });
});

describe("opencode model resolution (#1657)", () => {
  it("a stage model from stage config is the input the refusal checks, as dispatch uses it", () => {
    // pipeline.stage_models and the per-stage env override take bands only;
    // a provider-qualified value there is dropped by resolveModel, so dispatch
    // has no provider for it and the refusal must say so.
    configuredOpenCodeModel.value = "";
    process.env.NIGHTGAUGE_PIPELINE_STAGE_MODEL_FEATURE_DEV = "lmstudio/x";
    const onComplete = vi.fn();
    runStageSkillHeadless("feature-dev", 42, { onComplete });
    expect(spawn).not.toHaveBeenCalled();
    const outcome = onComplete.mock.calls[0]?.[0] as { success: boolean; error?: Error };
    expect(String(outcome.error?.message)).toMatch(/`opencode\.model`/);

    // The same stage with opencode.model set runs that model.
    vi.clearAllMocks();
    vi.mocked(spawn).mockReturnValue(createMockChildProcess());
    configuredOpenCodeModel.value = LOCAL_MODEL;
    runStageSkillHeadless("feature-dev", 42, {});
    expect(lastSpawnEnv().NIGHTGAUGE_MODEL).toBe(LOCAL_MODEL);
  });

  it("a performance-mode band on a local configured model keeps that model, source config", () => {
    const onModelResolved = vi.fn();
    dispatch("feature-dev", "opus", { onModelResolved });
    expect(lastSpawnEnv().NIGHTGAUGE_MODEL).toBe(LOCAL_MODEL);
    expect(onModelResolved).toHaveBeenCalledWith("feature-dev", LOCAL_MODEL, "opencode", "config");
  });

  it("a band on a hosted configured provider dispatches that provider's model for the band", () => {
    configuredOpenCodeModel.value = "anthropic/claude-sonnet-5";
    const onModelResolved = vi.fn();
    dispatch("feature-dev", "opus", { onModelResolved });
    const model = lastSpawnEnv().NIGHTGAUGE_MODEL;
    expect(model).toMatch(/^anthropic\/claude-opus-/);
    expect(onModelResolved.mock.calls[0][1]).toBe(model);
    expect(onModelResolved.mock.calls[0][3]).not.toBe("config");
  });

  it("with no opencode.model, a band is refused before spawn, whatever NIGHTGAUGE_MODEL says", () => {
    configuredOpenCodeModel.value = "";
    process.env.NIGHTGAUGE_MODEL = "lmstudio/operator-shell-model";
    const onComplete = vi.fn();
    dispatch("feature-dev", "opus", { onComplete });
    expect(spawn).not.toHaveBeenCalled();
    const outcome = onComplete.mock.calls[0]?.[0] as { success: boolean; error?: Error };
    expect(outcome.success).toBe(false);
    expect(String(outcome.error?.message)).toMatch(/`opencode\.model`/);
  });

  it("with no opencode.model, a provider-qualified stage model is dispatched as is", () => {
    configuredOpenCodeModel.value = "";
    process.env.NIGHTGAUGE_MODEL = "lmstudio/operator-shell-model";
    dispatch("feature-dev", "ollama/qwen3-coder:30b");
    expect(lastSpawnEnv().NIGHTGAUGE_MODEL).toBe("ollama/qwen3-coder:30b");
  });
});

/**
 * The stall WARNING is elapsed-based ("still running after …") for every
 * adapter; activity only moves the idle clock, which drives the stall KILL.
 * So liveness is asserted on the kill, with a 2-minute idle budget
 * (NIGHTGAUGE_PIPELINE_STALL_IDLE_MS) to make the window short.
 */
describe("opencode liveness (#1657)", () => {
  const IDLE_KILL_MS = 120_000;

  /**
   * What the SDK stage CLI prints on stdout when the OpenCode adapter reports
   * a `step_start` while its process runs (#1657), taken from the SDK's own
   * formatter rather than restated.
   */
  function sdkActivityLine(): string {
    const log = vi.spyOn(console, "log").mockImplementation(() => {});
    try {
      new OutputFormatter("json", "info").activity({ adapter: "opencode", event: "step_start" });
      return log.mock.calls[0][0] as string;
    } finally {
      log.mockRestore();
    }
  }

  beforeEach(() => {
    vi.useFakeTimers();
    process.env.NIGHTGAUGE_PIPELINE_STALL_IDLE_MS = String(IDLE_KILL_MS);
  });

  function killEvents(onStallEvent: ReturnType<typeof vi.fn>): unknown[] {
    return onStallEvent.mock.calls.filter(([e]) => (e as { action: string }).action === "kill");
  }

  it("the SDK's step_start activity lines for 10 simulated minutes keep a stage alive past its idle budget", () => {
    const STEP_START = sdkActivityLine();
    expect(STEP_START).toContain('"event":"step_start"');
    const onStallEvent = vi.fn();
    // A hosted model: no local floor, so only activity keeps it alive.
    dispatch("feature-planning", "anthropic/claude-sonnet-5", { onStallEvent });
    for (let elapsed = 0; elapsed < 10 * 60_000; elapsed += 60_000) {
      proc.stdout.emit("data", Buffer.from(`${STEP_START}\n`));
      vi.advanceTimersByTime(60_000);
    }
    expect(killEvents(onStallEvent)).toEqual([]);
    expect(proc.kill).not.toHaveBeenCalled();
  });

  it("the same stage with no lines is killed (the check can go red)", () => {
    const onStallEvent = vi.fn();
    dispatch("feature-planning", "anthropic/claude-sonnet-5", { onStallEvent });
    vi.advanceTimersByTime(10 * 60_000);
    expect(proc.kill).toHaveBeenCalled();
  });

  it("a local model's silent stage is neither warned about nor killed before the local floor", () => {
    const onStallEvent = vi.fn();
    const onStallWarning = vi.fn();
    dispatch("feature-planning", LOCAL_MODEL, { onStallEvent, onStallWarning });
    const warnFloorMs = LOCAL_PROVIDER_STALL_FLOOR.warnSec * 1000;
    const killFloorMs = LOCAL_PROVIDER_STALL_FLOOR.killSec * 1000;
    // Both configured thresholds sit below the floor.
    expect(warnFloorMs).toBeGreaterThan(DEFAULT_STALL_THRESHOLDS["feature-planning"] * 1000);
    expect(killFloorMs).toBeGreaterThan(IDLE_KILL_MS);

    vi.advanceTimersByTime(warnFloorMs - 10_000);
    expect(onStallWarning).not.toHaveBeenCalled();
    vi.advanceTimersByTime(20_000);
    expect(onStallWarning).toHaveBeenCalled();

    vi.advanceTimersByTime(killFloorMs - warnFloorMs - 20_000);
    expect(proc.kill).not.toHaveBeenCalled();
    vi.advanceTimersByTime(10 * 60_000);
    expect(proc.kill).toHaveBeenCalled();
  });

  it("a local stage that only reports activity is still killed at 8x the floored warn (nx-stall-multiple)", () => {
    delete process.env.NIGHTGAUGE_PIPELINE_STALL_IDLE_MS;
    const STEP_START = sdkActivityLine();
    const onStderr = vi.fn();
    dispatch("feature-dev", LOCAL_MODEL, { onStderr });
    const nxMs = LOCAL_PROVIDER_STALL_FLOOR.warnSec * 1000 * 8;
    const stderr = () => onStderr.mock.calls.map((c) => String(c[0])).join("");
    // Activity every minute keeps the idle clock fresh, but nothing productive
    // happens, so the Nx ceiling is what ends it.
    for (let t = 0; t < nxMs - 60_000; t += 60_000) {
      proc.stdout.emit("data", Buffer.from(`${STEP_START}\n`));
      vi.advanceTimersByTime(60_000);
    }
    expect(proc.kill).not.toHaveBeenCalled();
    for (let t = 0; t < 10 * 60_000 && !vi.mocked(proc.kill).mock.calls.length; t += 60_000) {
      proc.stdout.emit("data", Buffer.from(`${STEP_START}\n`));
      vi.advanceTimersByTime(60_000);
    }
    expect(proc.kill).toHaveBeenCalled();
    expect(stderr()).toMatch(/nx-stall-multiple/);
  });
});
