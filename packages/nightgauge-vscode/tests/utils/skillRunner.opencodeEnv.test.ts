/** The Go verb's real output for LOCAL_MODEL (#1648's golden, generated by the verb). */
async function goldenVerb(): Promise<{
  env: Record<string, string>;
  config_content: string;
  env_withhold: { prefixes: string[]; names: string[] };
}> {
  // `fs` is mocked for the dispatch; the golden is read with the real one.
  const realFs = await vi.importActual<typeof import("fs")>("fs");
  const file = path.resolve(
    __dirname,
    "../../../../internal/execution/adapters/testdata/opencode_config_golden.json"
  );
  const golden = JSON.parse(realFs.readFileSync(file, "utf-8").split("@BASE@").join("/base")) as {
    inputs: { model: string };
    verb: {
      env: Record<string, string>;
      config_content: string;
      env_withhold: { prefixes: string[]; names: string[] };
    };
  };
  expect(golden.inputs.model).toBe(LOCAL_MODEL);
  return golden.verb;
}

function lastSpawnEnv(): Record<string, string> {
  const calls = vi.mocked(spawn).mock.calls;
  expect(calls.length, "spawn was not called").toBeGreaterThan(0);
  const opts = calls[calls.length - 1][2] as { env?: Record<string, string> };
  return opts?.env ?? {};
}

/** Dispatch one opencode stage with `model` as the stage's model. */
function dispatch(
  stage: "feature-dev" | "feature-planning",
  model: string,
  callbacks: Parameters<typeof runStageSkillHeadless>[2] = {}
) {
  return runStageSkillHeadless(stage, 42, callbacks, undefined, undefined, undefined, model);
}

