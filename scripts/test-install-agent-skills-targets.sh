#!/usr/bin/env bash
# Regression tests for install-agent-skills.sh Claude/Codex/Grok/OpenCode targets.
#
# The installer used to copy skills for Claude plugins and Codex only. Grok
# then saw Nightgauge skills only by scanning Claude's plugin cache, so
# `grok plugin list` was empty and `~/.grok/skills` did not exist. These arms
# pin the home-skills copy for Grok and Codex, the --*-only flags, and the
# skip-when-absent path — against a throwaway HOME, never the operator's
# real ~/.codex or ~/.grok, and a sandbox copy of the repository, never this
# checkout, whose committed plugin-skills mirror the installer would rewrite.
#
# Arm (vacuous) copies the installer, comments out the install_grok call, and
# asserts --grok-only then leaves ~/.grok/skills empty. Without that, a test
# that never looked at dest could still pass.
#
# Arms (g) and (g2) prove the suite never wrote the checkout: `git status
# --porcelain` is unchanged, and the committed mirror was not even rewritten
# with identical bytes, which `git status` cannot see.
#
# Run: bash scripts/test-install-agent-skills-targets.sh
# Also run by .github/workflows/lint.yml and scripts/ci-local.sh.
set -uo pipefail
# `cd ""` succeeds in bash, so a failed rev-parse must stop the suite here or
# it carries on in the caller's directory (#1694).
if ! TOPLEVEL="$(git rev-parse --show-toplevel)" || ! cd "$TOPLEVEL"; then
  echo "FAIL: not inside a git work tree; nothing was tested" >&2
  exit 1
fi

REPO_ROOT="$(pwd)"
PASS=0
FAIL=0
TMP=""

# shellcheck disable=SC2329 # invoked by the trap below
cleanup() {
  [ -n "$TMP" ] && rm -rf "$TMP"
  return 0
}
trap cleanup EXIT

ok() {
  PASS=$((PASS + 1))
  echo "  ok   $1"
}

nope() {
  FAIL=$((FAIL + 1))
  echo "  FAIL $1"
}

TMP="$(mktemp -d)"

# `--no-optional-locks` keeps this read from taking .git/index.lock, which a
# concurrent git command in the same checkout could then fail on.
checkout_status() {
  git --no-optional-locks status --porcelain --untracked-files=all
}
if ! STATUS_BEFORE="$(checkout_status)"; then
  echo "FAIL: git status failed before the suite ran; cannot prove it is read-only" >&2
  exit 1
fi

# The installer derives REPO_ROOT from its own path and always regenerates
# <REPO_ROOT>/claude-plugins/nightgauge/skills first, so every arm runs a copy
# of it inside a sandbox, never the checkout's own copy. The skills come from
# HEAD, so an arm sees only what it sets up. The installer and its link helper
# are the working-tree copies, so an uncommitted edit to them is what gets
# tested. Arms (g) and (g2) prove the checkout is left alone.
SANDBOX="$TMP/repo"
mkdir -p "$SANDBOX/scripts/lib"
if ! git archive HEAD skills | tar -x -C "$SANDBOX"; then
  echo "FAIL: could not seed the sandbox from git archive HEAD" >&2
  exit 1
fi
cp scripts/install-agent-skills.sh "$SANDBOX/scripts/"
cp scripts/lib/mirror_links.py scripts/lib/install_skill_tree.py "$SANDBOX/scripts/lib/"
INSTALLER="$SANDBOX/scripts/install-agent-skills.sh"

# PATH with the real claude/codex/grok CLIs stripped so the installer cannot
# write into the operator's plugin caches. Keep rsync/python3/node/git.
filter_path() {
  local filtered="" d
  local IFS=':'
  for d in $PATH; do
    [ -z "$d" ] && continue
    if [ -x "$d/grok" ] || [ -x "$d/claude" ] || [ -x "$d/codex" ]; then
      continue
    fi
    filtered="${filtered:+$filtered:}$d"
  done
  printf '%s\n' "$filtered"
}
SAFE_PATH="$(filter_path)"

# Path, inode, mtime, ctime and size of every entry in the checkout's committed
# mirror. The installer regenerates the mirror by deleting and recreating each
# skill directory, so any installer run against this checkout changes the
# listing even when the regenerated bytes are identical. ctime is here because
# `rsync -a` restores mtimes and a filesystem may reuse a freed inode number;
# nothing can set ctime back.
CHECKOUT_MIRROR="$REPO_ROOT/claude-plugins/nightgauge/skills"
mirror_fingerprint() {
  python3 - "$CHECKOUT_MIRROR" <<'PY'
import os, sys
root = sys.argv[1]
rows = []
for dirpath, dirnames, filenames in os.walk(root):
    for name in [""] + dirnames + filenames:
        path = os.path.join(dirpath, name) if name else dirpath
        st = os.lstat(path)
        rows.append(
            f"{os.path.relpath(path, root)}\t{st.st_ino}\t{st.st_mtime_ns}"
            f"\t{st.st_ctime_ns}\t{st.st_size}"
        )
print("\n".join(sorted(rows)))
PY
}
MIRROR_BEFORE="$(mirror_fingerprint)"
# An empty listing would make (g2) compare nothing with nothing.
if [ -z "$MIRROR_BEFORE" ]; then
  echo "FAIL: could not fingerprint $CHECKOUT_MIRROR; (g2) would prove nothing" >&2
  exit 1
fi

# --- (a) default install copies Codex + Grok when both dest roots exist -----
HOME_A="$TMP/home-a"
mkdir -p "$HOME_A/.codex" "$HOME_A/.grok"
if HOME="$HOME_A" PATH="$SAFE_PATH" bash "$INSTALLER" >/dev/null 2>"$TMP/a.err"; then
  if [ -f "$HOME_A/.grok/skills/nightgauge-issue-create/SKILL.md" ] &&
    [ -f "$HOME_A/.grok/skills/nightgauge-issue-create/_includes/environment-and-content.md" ] &&
    [ -f "$HOME_A/.grok/skills/_shared/PREFLIGHT.md" ] &&
    [ -f "$HOME_A/.codex/skills/nightgauge-issue-create/SKILL.md" ]; then
    ok "(a) default install copies Codex and Grok skills (incl. _includes + _shared)"
  else
    nope "(a) expected Codex and Grok dest files after default install"
    find "$HOME_A" -name SKILL.md | sed -n '1,10p'
  fi
else
  nope "(a) default install exited non-zero"
  sed 's/^/    /' "$TMP/a.err"
fi

if grep -q "disable-model-invocation" "$HOME_A/.grok/skills/nightgauge-issue-create/SKILL.md" 2>/dev/null; then
  nope "(a2) Grok copy must not receive disable-model-invocation"
else
  ok "(a2) Grok copy has no disable-model-invocation"
fi

# --- (b) --grok-only does not touch Codex dest ------------------------------
HOME_B="$TMP/home-b"
mkdir -p "$HOME_B/.codex" "$HOME_B/.grok"
if HOME="$HOME_B" PATH="$SAFE_PATH" bash "$INSTALLER" --grok-only >/dev/null 2>"$TMP/b.err"; then
  if [ -f "$HOME_B/.grok/skills/nightgauge-issue-create/SKILL.md" ] &&
    [ ! -e "$HOME_B/.codex/skills" ]; then
    ok "(b) --grok-only installs Grok and leaves Codex dest untouched"
  else
    nope "(b) --grok-only touched Codex or missed Grok"
    find "$HOME_B" | sed -n '1,10s/^/    /p'
  fi
else
  nope "(b) --grok-only exited non-zero"
  sed 's/^/    /' "$TMP/b.err"
fi

# --- (c) --codex-only does not touch Grok dest ------------------------------
HOME_C="$TMP/home-c"
mkdir -p "$HOME_C/.codex" "$HOME_C/.grok"
if HOME="$HOME_C" PATH="$SAFE_PATH" bash "$INSTALLER" --codex-only >/dev/null 2>"$TMP/c.err"; then
  if [ -f "$HOME_C/.codex/skills/nightgauge-issue-create/SKILL.md" ] &&
    [ ! -e "$HOME_C/.grok/skills" ]; then
    ok "(c) --codex-only installs Codex and leaves Grok dest untouched"
  else
    nope "(c) --codex-only touched Grok or missed Codex"
    find "$HOME_C" | sed -n '1,10s/^/    /p'
  fi
else
  nope "(c) --codex-only exited non-zero"
  sed 's/^/    /' "$TMP/c.err"
fi

# --- (d) neither grok binary nor ~/.grok → skip, exit 0 ---------------------
HOME_D="$TMP/home-d"
mkdir -p "$HOME_D"
if HOME="$HOME_D" PATH="$SAFE_PATH" bash "$INSTALLER" --grok-only >"$TMP/d.out" 2>"$TMP/d.err"; then
  if [ ! -e "$HOME_D/.grok" ] && grep -q "skipping" "$TMP/d.out" "$TMP/d.err"; then
    ok "(d) grok install skipped when neither CLI nor ~/.grok exists (exit 0)"
  else
    nope "(d) skip path did not skip, or created ~/.grok"
    cat "$TMP/d.out" "$TMP/d.err"
    find "$HOME_D" | sed -n '1,10s/^/    /p'
  fi
else
  nope "(d) skip path exited non-zero"
  cat "$TMP/d.out" "$TMP/d.err"
fi

# --- (e) --claude-only installs neither Codex nor Grok dest -----------------
HOME_E="$TMP/home-e"
mkdir -p "$HOME_E/.codex" "$HOME_E/.grok"
if HOME="$HOME_E" PATH="$SAFE_PATH" bash "$INSTALLER" --claude-only >/dev/null 2>"$TMP/e.err"; then
  if [ ! -e "$HOME_E/.codex/skills" ] && [ ! -e "$HOME_E/.grok/skills" ]; then
    ok "(e) --claude-only leaves Codex and Grok dests untouched"
  else
    nope "(e) --claude-only copied Codex or Grok skills"
    find "$HOME_E" | sed -n '1,10s/^/    /p'
  fi
else
  nope "(e) --claude-only exited non-zero"
  sed 's/^/    /' "$TMP/e.err"
fi

# --- (f) commenting out install_grok makes --grok-only miss dest ------------
# The installer computes REPO_ROOT from its own path, so the copy is patched
# to keep pointing at the sandbox while the grok call is disabled.
BROKEN="$TMP/broken-install.sh"
python3 - "$INSTALLER" "$BROKEN" "$SANDBOX" <<'PY'
import sys
src, dest, repo = sys.argv[1], sys.argv[2], sys.argv[3]
text = open(src, encoding="utf-8").read()
text = text.replace(
    'SCRIPT_DIR="$(cd "$(dirname "$0")" && pwd)"',
    f'SCRIPT_DIR="{repo}/scripts"',
    1,
)
text = text.replace(
    'REPO_ROOT="$(cd "$SCRIPT_DIR/.." && pwd)"',
    f'REPO_ROOT="{repo}"',
    1,
)
old = '[ "$DO_GROK" = "1" ] && install_grok'
if old not in text:
    raise SystemExit("install_grok call site not found — test cannot prove vacuity")
text = text.replace(old, ': # install_grok disabled for vacuous-test arm', 1)
open(dest, "w", encoding="utf-8").write(text)
PY
chmod +x "$BROKEN"
HOME_F="$TMP/home-f"
mkdir -p "$HOME_F/.grok"
if HOME="$HOME_F" PATH="$SAFE_PATH" bash "$BROKEN" --grok-only >/dev/null 2>"$TMP/f.err"; then
  if [ -f "$HOME_F/.grok/skills/nightgauge-issue-create/SKILL.md" ]; then
    nope "(f) --grok-only still copied skills after install_grok was disabled (vacuous test)"
  else
    ok "(f) --grok-only with install_grok disabled does not populate ~/.grok/skills"
  fi
else
  # A disabled grok install must still exit 0 (best-effort skip).
  nope "(f) patched installer exited non-zero"
  sed 's/^/    /' "$TMP/f.err"
fi

# --- (h*) ownership and containment (#1694) --------------------------------
# The Codex and Grok copies used to `rsync -a --delete` over any directory whose
# name matched a Nightgauge skill, and to copy source symlinks as links, so a
# link to ~/.ssh in skills/ landed in the agent's skill directory.
MARKER=".nightgauge-installed"

# (h1) an operator's own update-docs and another pack's _shared survive, named
# in a warning; a directory carrying the marker is replaced.
HOME_H1="$TMP/home-h1"
for root in "$HOME_H1/.codex/skills" "$HOME_H1/.grok/skills"; do
  mkdir -p "$root/update-docs" "$root/_shared" "$root/nightgauge-retro"
  echo mine >"$root/update-docs/mine.md"
  echo theirs >"$root/_shared/theirs.md"
  : >"$root/nightgauge-retro/$MARKER"
  echo stale >"$root/nightgauge-retro/stale.md"
done
if HOME="$HOME_H1" PATH="$SAFE_PATH" bash "$INSTALLER" >"$TMP/h1.out" 2>"$TMP/h1.err"; then
  nope "(h1) an install that skipped skills exited 0"
else
  h1_ok=1
  for root in "$HOME_H1/.codex/skills" "$HOME_H1/.grok/skills"; do
    [ "$(cat "$root/update-docs/mine.md" 2>/dev/null)" = mine ] &&
      [ ! -e "$root/update-docs/SKILL.md" ] && [ ! -e "$root/update-docs/$MARKER" ] &&
      [ "$(cat "$root/_shared/theirs.md" 2>/dev/null)" = theirs ] &&
      [ ! -e "$root/_shared/PREFLIGHT.md" ] || h1_ok=0
    [ -f "$root/nightgauge-retro/SKILL.md" ] && [ -f "$root/nightgauge-retro/$MARKER" ] &&
      [ ! -e "$root/nightgauge-retro/stale.md" ] &&
      [ -f "$root/nightgauge-issue-create/$MARKER" ] || h1_ok=0
  done
  if [ "$h1_ok" = 1 ] && grep -q "skipped update-docs" "$TMP/h1.err" &&
    grep -q "skipped _shared" "$TMP/h1.err" &&
    grep -Eq "Codex: installed [0-9]+ of [0-9]+, skipped 2" "$TMP/h1.out" &&
    grep -Eq "Grok: installed [0-9]+ of [0-9]+, skipped 2" "$TMP/h1.out" &&
    grep -q "Agent skill sync INCOMPLETE: Codex and Grok" "$TMP/h1.err" &&
    ! grep -q "Agent skill sync complete" "$TMP/h1.out"; then
    ok "(h1) unowned dirs survive, the count is reported and Grok still ran after Codex skipped"
  else
    nope "(h1) an unowned directory was replaced, a marked one was not, or no warning"
    sed 's/^/    /' "$TMP/h1.out" "$TMP/h1.err"
  fi
fi

# (h2) a symlink at a skill's destination is the operator's: left in place,
# and nothing is written through it.
HOME_H2="$TMP/home-h2"
mkdir -p "$HOME_H2/.codex/skills" "$HOME_H2/linked-target"
ln -s "$HOME_H2/linked-target" "$HOME_H2/.codex/skills/nightgauge-issue-create"
if ! HOME="$HOME_H2" PATH="$SAFE_PATH" bash "$INSTALLER" --codex-only >"$TMP/h2.out" 2>"$TMP/h2.err" &&
  grep -Eq "installed [0-9]+ of [0-9]+, skipped 1" "$TMP/h2.out" &&
  [ -L "$HOME_H2/.codex/skills/nightgauge-issue-create" ] &&
  [ -z "$(ls -A "$HOME_H2/linked-target")" ] &&
  grep -q "skipped nightgauge-issue-create" "$TMP/h2.err"; then
  ok "(h2) a symlinked skill destination is left alone and not written through"
else
  nope "(h2) the installer replaced or wrote through a symlinked skill destination"
  sed 's/^/    /' "$TMP/h2.err"
fi

# (h3) source symlinks: a SKILL.md and a file linked out of the tree are not
# installed; a link to a file inside the tree lands as a regular file.
SBH="$TMP/sbh"
mkdir -p "$SBH"
cp -R "$SANDBOX/." "$SBH/"
mkdir -p "$TMP/outside" "$SBH/skills/nightgauge-leaky"
printf -- '---\nname: leaky\ndescription: Outside.\n---\n' >"$TMP/outside/SKILL.md"
echo 'not for agents' >"$TMP/outside/secret"
ln -s "$TMP/outside/SKILL.md" "$SBH/skills/nightgauge-leaky/SKILL.md"
ln -s "$TMP/outside/secret" "$SBH/skills/nightgauge-issue-create/leak.md"
ln -s ../_shared/PREFLIGHT.md "$SBH/skills/nightgauge-issue-create/preflight-alias.md"
HOME_H3="$TMP/home-h3"
mkdir -p "$HOME_H3/.codex"
if HOME="$HOME_H3" PATH="$SAFE_PATH" bash "$SBH/scripts/install-agent-skills.sh" --codex-only \
  >/dev/null 2>"$TMP/h3.err"; then
  D3="$HOME_H3/.codex/skills"
  if [ ! -e "$D3/nightgauge-leaky" ] && [ ! -e "$D3/nightgauge-issue-create/leak.md" ] &&
    [ ! -L "$D3/nightgauge-issue-create/leak.md" ] &&
    [ -f "$D3/nightgauge-issue-create/preflight-alias.md" ] &&
    [ ! -L "$D3/nightgauge-issue-create/preflight-alias.md" ] &&
    [ -z "$(find "$D3" -type l)" ] &&
    grep -q "nightgauge-leaky/SKILL.md" "$TMP/h3.err" &&
    grep -q "leak.md" "$TMP/h3.err"; then
    ok "(h3) source links out of skills/ are skipped and named; an inside link lands as a file"
  else
    nope "(h3) a link out of skills/ was installed, or an inside link was not copied"
    find "$D3" -name 'leak*' -o -name 'nightgauge-leaky' -o -type l | sed 's/^/    /'
    sed 's/^/    /' "$TMP/h3.err"
  fi
else
  nope "(h3) install exited non-zero"
  sed 's/^/    /' "$TMP/h3.err"
fi
# OpenCode copies through the same helper.
HOME_H3O="$TMP/home-h3o"
mkdir -p "$HOME_H3O"
if oc_bin="$TMP/h3o-bin" && mkdir -p "$oc_bin" && printf '#!/bin/sh\nexit 0\n' >"$oc_bin/opencode" &&
  chmod +x "$oc_bin/opencode" &&
  HOME="$HOME_H3O" XDG_CONFIG_HOME="$HOME_H3O/xdg" PATH="$oc_bin:$SAFE_PATH" \
    bash "$SBH/scripts/install-agent-skills.sh" --opencode-only --yes >/dev/null 2>"$TMP/h3o.err"; then
  if [ -f "$HOME_H3O/xdg/opencode/skills/nightgauge-issue-create/SKILL.md" ] &&
    [ ! -e "$HOME_H3O/xdg/opencode/skills/nightgauge-issue-create/leak.md" ] &&
    [ -z "$(find "$HOME_H3O/xdg/opencode/skills" -type l)" ]; then
    ok "(h3o) the OpenCode copy skips a link out of skills/ too"
  else
    nope "(h3o) the OpenCode copy installed a link out of skills/"
  fi
else
  nope "(h3o) --opencode-only exited non-zero on the linked sandbox"
  sed 's/^/    /' "$TMP/h3o.err"
fi

# (h4) a destination root that resolves into the checkout is refused before
# anything is written: ~/.codex/skills linked to the source skills/ itself
# would otherwise get markers written into, and directories replaced in, the
# canonical tree.
SBH4="$TMP/sbh4"
mkdir -p "$SBH4"
cp -R "$SANDBOX/." "$SBH4/"
HOME_H4="$TMP/home-h4"
mkdir -p "$HOME_H4/.codex"
ln -s "$SBH4/skills" "$HOME_H4/.codex/skills"
SUM_H4="$(cd "$SBH4/skills" && find . -type f | sort | xargs shasum -a 256)"
if HOME="$HOME_H4" PATH="$SAFE_PATH" bash "$SBH4/scripts/install-agent-skills.sh" --codex-only \
  >/dev/null 2>"$TMP/h4.err"; then
  nope "(h4) a destination root inside the checkout was accepted"
elif [ "$(cd "$SBH4/skills" && find . -type f | sort | xargs shasum -a 256)" = "$SUM_H4" ] &&
  grep -q "refusing to install" "$TMP/h4.err"; then
  ok "(h4) a destination root resolving into the checkout is refused, nothing written"
else
  nope "(h4) refused, but the canonical skills/ changed first"
  sed 's/^/    /' "$TMP/h4.err"
fi

# --- (j) --adopt and retired skills (#2739) --------------------------------
# A real git repository with two versions of one skill and an old _shared
# file, so the shipped set has history to prove against. Its installer is the
# working-tree copy, like every other arm.
SBJ="$TMP/sbj"
j_git() { git -C "$SBJ" -c user.name=t -c user.email=t@example.com "$@"; }
mkdir -p "$SBJ/scripts"
cp -R "$SANDBOX/skills" "$SBJ/skills"
cp -R "$SANDBOX/scripts/." "$SBJ/scripts/"
j_old="$TMP/j-old-skill.md"
cp "$SBJ/skills/nightgauge-retro/SKILL.md" "$j_old"
j_old_shared="$TMP/j-old-shared.md"
cp "$SBJ/skills/_shared/PREFLIGHT.md" "$j_old_shared"
if ! git init -q "$SBJ" || ! j_git add -A || ! j_git commit -qm old; then
  nope "(j0) could not build the adopt sandbox; no (j) arm ran"
else
  echo "# a later version" >>"$SBJ/skills/nightgauge-retro/SKILL.md"
  echo "# a later version" >>"$SBJ/skills/_shared/PREFLIGHT.md"
  j_git add -A && j_git commit -qm new
  j_seed() {
    local root="$1/.codex/skills"
    mkdir -p "$root/nightgauge-retro" "$root/_shared" "$root/nightgauge-issue-create"
    cp "$j_old" "$root/nightgauge-retro/SKILL.md"
    cp "$j_old_shared" "$root/_shared/PREFLIGHT.md"
    echo "my edit" >"$root/nightgauge-issue-create/SKILL.md"
  }

  # (j1) a shipped old copy is replaced and moved outside the root; a local
  # edit stays and is named; the run is still non-zero because of it.
  HOME_J1="$TMP/home-j1"
  j_seed "$HOME_J1"
  J_INSTALLER="$SBJ/scripts/install-agent-skills.sh"
  if HOME="$HOME_J1" PATH="$SAFE_PATH" bash "$J_INSTALLER" --codex-only --adopt \
    >"$TMP/j1.out" 2>"$TMP/j1.err"; then
    nope "(j1) --adopt exited 0 with a locally edited directory left behind"
  else
    root="$HOME_J1/.codex/skills"
    aside="$(find "$root.nightgauge-adopted" -type f -path '*/nightgauge-retro/SKILL.md' 2>/dev/null)"
    shared_aside="$(find "$root.nightgauge-adopted" -type f -path '*/_shared/PREFLIGHT.md' 2>/dev/null)"
    if [ -f "$root/nightgauge-retro/$MARKER" ] &&
      cmp -s "$root/nightgauge-retro/SKILL.md" "$SBJ/skills/nightgauge-retro/SKILL.md" &&
      [ -n "$aside" ] && cmp -s "$aside" "$j_old" &&
      [ -f "$root/_shared/$MARKER" ] && [ -n "$shared_aside" ] &&
      [ "$(cat "$root/nightgauge-issue-create/SKILL.md")" = "my edit" ] &&
      [ ! -e "$root/nightgauge-issue-create/$MARKER" ] &&
      grep -q "skipped nightgauge-issue-create" "$TMP/j1.err" &&
      grep -Eq "skipped 1, adopted 2" "$TMP/j1.out"; then
      ok "(j1) --adopt replaces shipped copies, keeps them outside the root, leaves local edits"
    else
      nope "(j1) --adopt did the wrong thing to a shipped or a locally edited directory"
      sed 's/^/    /' "$TMP/j1.out" "$TMP/j1.err"
    fi
  fi

  # (j2) without --adopt the very same home is skipped: the proof is the flag's.
  HOME_J2="$TMP/home-j2"
  j_seed "$HOME_J2"
  if ! HOME="$HOME_J2" PATH="$SAFE_PATH" bash "$J_INSTALLER" --codex-only \
    >"$TMP/j2.out" 2>"$TMP/j2.err" &&
    [ ! -e "$HOME_J2/.codex/skills/nightgauge-retro/$MARKER" ] &&
    [ ! -e "$HOME_J2/.codex/skills.nightgauge-adopted" ] &&
    grep -Eq "skipped 3$" "$TMP/j2.out"; then
    ok "(j2) a plain install adopts nothing"
  else
    nope "(j2) a plain install touched a marker-less directory"
    sed 's/^/    /' "$TMP/j2.out" "$TMP/j2.err"
  fi

  # (j3) a symlink at a skill's destination is never adopted, even with --adopt.
  HOME_J3="$TMP/home-j3"
  mkdir -p "$HOME_J3/.codex/skills" "$TMP/j3-target"
  cp "$j_old" "$TMP/j3-target/SKILL.md"
  ln -s "$TMP/j3-target" "$HOME_J3/.codex/skills/nightgauge-retro"
  if ! HOME="$HOME_J3" PATH="$SAFE_PATH" bash "$J_INSTALLER" --codex-only --adopt \
    >"$TMP/j3.out" 2>"$TMP/j3.err" &&
    [ -L "$HOME_J3/.codex/skills/nightgauge-retro" ] &&
    cmp -s "$TMP/j3-target/SKILL.md" "$j_old"; then
    ok "(j3) --adopt leaves a symlink alone"
  else
    nope "(j3) --adopt touched a symlinked skill"
    sed 's/^/    /' "$TMP/j3.out" "$TMP/j3.err"
  fi

  # (j4) a shallow clone cannot prove anything: exit 1, nothing written.
  SBJS="$TMP/sbj-shallow"
  git clone -q --depth 1 "file://$SBJ" "$SBJS"
