# --- (g) the suite never wrote the checkout it runs in ----------------------
# ci-local.sh runs this suite concurrently with the read-only mirror drift gate,
# and lint.yml runs it just before that gate. A run that regenerated the
# checkout's mirror would make the gate read a half-rebuilt tree locally, and in
# CI would repair a stale committed mirror before the gate could see it. The
# comparison covers this whole work tree: every step that can overlap this one
# in ci-local.sh is read-only by contract, so any new entry is a real write.
if ! STATUS_AFTER="$(checkout_status)"; then
  nope "(g) git status failed after the suite ran"
elif [ "$STATUS_AFTER" = "$STATUS_BEFORE" ]; then
  ok "(g) git status --porcelain is unchanged by the suite"
else
  nope "(g) the suite changed git status --porcelain (before -> after):"
  diff <(printf '%s\n' "$STATUS_BEFORE") <(printf '%s\n' "$STATUS_AFTER") | sed 's/^/    /'
fi

